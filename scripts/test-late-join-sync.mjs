const flush = async () => { for (let i = 0; i < 20; i += 1) await Promise.resolve(); };
function observe(promise) {
  const result = { state: 'pending', error: null };
  result.done = Promise.resolve(promise).then(
    () => { result.state = 'fulfilled'; },
    (error) => { result.state = 'rejected'; result.error = error; },
  );
  return result;
}

// This is the exact key format generated by createLocalBoardLibrary (28 bytes).
const ownerKey = Buffer.alloc(28, 42).toString('base64url');

test('late join: an owner URL on a clean device uses the existing share-key room', async () => {
  let created = 0;
  const repository = createBrowserBoardRepository({
    getBoard: async () => null,
    getReplica: () => null,
    createAuthorityRecord: async () => { created += 1; throw new Error('Must not create an empty authority'); },
  });
  const access = await repository.getBoardAccess('late-join-board', ownerKey);
  assert.equal(access.realtimeKey, await deriveShareKey(ownerKey));
  assert.equal(access.permission, 'edit', 'an owner URL alone must not create a competing local authority');
  assert.equal(access.snapshot, null);
  assert.equal(created, 0);
});

test('late join: guest URLs retain their room key unchanged', async () => {
  const shareKey = await deriveShareKey(ownerKey);
  const repository = createBrowserBoardRepository({ getBoard: async () => null, getReplica: () => null });
  const access = await repository.getBoardAccess('late-join-board', shareKey);
  assert.equal(access.realtimeKey, shareKey);
});

test('late join: a clean replica requests a full snapshot and installs it once', async (t) => {
  const sent = [];
  const installed = [];
  let revision = 0;
  const session = createStudentPeerSession({
    transport: { send: async (type, payload) => { sent.push({ type, payload }); } },
    getRevision: () => revision,
    applyCommit: async () => assert.fail('a clean board must not replay its entire drawing history'),
    installSnapshot: async (snapshot, nextRevision) => { installed.push(snapshot); revision = nextRevision; },
  });
  const starting = observe(session.start());
  t.after(async () => { session.close(); await starting.done; });
  await flush();
  assert.equal(sent[0]?.type, 'snapshot-request');
  assert.equal(starting.state, 'pending');
  const snapshot = { version: 2, background: 'grid', canvas: { objects: [
    { boardObjectId: 'text-1', type: 'IText', text: 'Already on the board' },
    { boardObjectId: 'stroke-1', type: 'Path', path: [['M', 0, 0], ['L', 20, 20]] },
  ] } };
  await session.handleTransfer({ kind: 'snapshot', text: JSON.stringify({ snapshot, revision: 42 }) });
  await starting.done;
  assert.equal(starting.state, 'fulfilled');
  assert.equal(revision, 42);
  assert.deepEqual(installed, [snapshot]);
});

test('late join: a head at revision zero is not a substitute for the initial snapshot', async (t) => {
  const session = createStudentPeerSession({
    transport: { send: async () => {} }, getRevision: () => 0,
    applyCommit: async () => {}, installSnapshot: async () => {},
  });
  const starting = observe(session.start());
  t.after(async () => { session.close(); await starting.done; });
  await session.handleMessage({ type: 'head', payload: { revision: 0 } });
  await flush();
  assert.equal(starting.state, 'pending', 'a prepopulated revision-zero snapshot has not arrived yet');
  await session.handleTransfer({ kind: 'snapshot', text: JSON.stringify({
    revision: 0, snapshot: { version: 2, canvas: { objects: [{ boardObjectId: 'imported' }] } },
  }) });
  await starting.done;
  assert.equal(starting.state, 'fulfilled');
});

test('late join: failed snapshot installation rejects startup instead of waiting forever', async (t) => {
  const failure = new Error('Snapshot rendering failed');
  const session = createStudentPeerSession({
    transport: { send: async () => {} }, getRevision: () => 0,
    applyCommit: async () => {}, installSnapshot: async () => { throw failure; },
  });
  const starting = observe(session.start());
  t.after(async () => { session.close(); await starting.done; });
  await assert.rejects(session.handleTransfer({ kind: 'snapshot', text: JSON.stringify({
    snapshot: { version: 2, canvas: { objects: [] } }, revision: 1,
  }) }), /Snapshot rendering failed/);
  await flush();
  assert.equal(starting.state, 'rejected');
  assert.equal(starting.error, failure);
});

function pendingNetwork({ stalledSignaling = false } = {}) {
  const state = { connectionOptions: null, transportOptions: null, closed: 0, states: [] };
  state.network = createStudentPeerNetwork({
    teacherId: 'teacher', signaling: { send: async () => {} },
    getRevision: () => 0, applyCommit: async () => {}, installSnapshot: async () => {},
    connectTimeoutMs: 100, initialSyncTimeoutMs: 100,
    onState: (value) => { state.states.push(value); },
    createConnection: (options) => {
      state.connectionOptions = options;
      return { start: () => stalledSignaling ? new Promise(() => {}) : Promise.resolve(),
        handleSignal: async () => {}, close: () => { state.closed += 1; } };
    },
    createTransport: (options) => {
      state.transportOptions = options;
      return { send: async () => {}, close() {} };
    },
    createSession: () => ({ start: () => new Promise(() => {}), close() {} }),
  });
  return state;
}

for (const stalledSignaling of [false, true]) {
  test(`late join: connection deadline releases startup (stalled signaling=${stalledSignaling})`, async (t) => {
    t.mock.timers.enable({ apis: ['setTimeout'] });
    const fixture = pendingNetwork({ stalledSignaling });
    const starting = observe(fixture.network.start());
    t.after(() => fixture.network.close());
    await flush();
    t.mock.timers.tick(101);
    await flush();
    assert.equal(starting.state, 'rejected');
    assert.match(starting.error.message, /timed out/i);
    assert.equal(fixture.network.isReady(), false);
    assert.equal(fixture.closed, 1);
    assert.ok(fixture.states.includes('failed'));
  });
}

test('late join: active snapshot transfer extends the idle deadline, a stalled transfer fails', async (t) => {
  t.mock.timers.enable({ apis: ['setTimeout'] });
  const fixture = pendingNetwork();
  const starting = observe(fixture.network.start());
  t.after(() => fixture.network.close());
  await flush();
  fixture.connectionOptions.onChannel({ label: 'alex-board-durable-v1' });
  await flush();
  for (let i = 0; i < 5; i += 1) {
    t.mock.timers.tick(80);
    fixture.transportOptions.onProgress?.();
    await flush();
    assert.equal(starting.state, 'pending', 'active transfer must not hit a total-size deadline');
  }
  t.mock.timers.tick(101);
  await flush();
  assert.equal(starting.state, 'rejected');
  assert.match(starting.error.message, /timed out/i);
  assert.equal(fixture.closed, 1);
});

test('late join: transport reports progress only for valid protocol frames', () => {
  const channel = Object.assign(new EventTarget(), { readyState: 'open', send() {} });
  let progress = 0;
  const transport = createPeerDataChannelTransport({ channel, onProgress: () => { progress += 1; } });
  try {
    channel.dispatchEvent(new MessageEvent('message', { data: createPeerMessage('head', { revision: 2 }) }));
    assert.equal(progress, 1);
    channel.dispatchEvent(new MessageEvent('message', { data: 'not-json' }));
    assert.equal(progress, 1);
  } finally { transport.close(); }
});
